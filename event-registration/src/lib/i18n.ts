export const dictionaries: Record<Locale, Dict> = { de, en, sq, bs, hr, sr, tr };

/** Saved choice (cookie) first, then the browser's languages, then German. */
export function pickLocale(cookieValue: string | undefined, acceptLanguage: string | null): Locale {
  if (cookieValue && (LOCALES as string[]).includes(cookieValue)) return cookieValue as Locale;
  for (const part of (acceptLanguage || "").split(",")) {
    const base = part.split(";")[0].trim().toLowerCase().split("-")[0];
    if ((LOCALES as string[]).includes(base)) return base as Locale;
    if (base === "sh" || base === "cnr") return "sr"; // Serbo-Croatian / Montenegrin
  }
  return DEFAULT_LOCALE;
}

export function intlTag(locale: Locale): string {
  return LANGUAGES.find((l) => l.code === locale)?.intl ?? "de-DE";
}
