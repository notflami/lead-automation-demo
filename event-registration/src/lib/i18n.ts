export const dictionaries: Record<Locale, Dict> = { en, de };

export function pickLocale(cookieValue: string | undefined, acceptLanguage: string | null): Locale {
  if (cookieValue === "en" || cookieValue === "de") return cookieValue;
  const first = (acceptLanguage || "").split(",")[0]?.trim().toLowerCase() || "";
  return first.startsWith("de") ? "de" : "en";
}
